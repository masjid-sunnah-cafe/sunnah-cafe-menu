-- Sunnah Cafe order schema. Run after schema.sql.

create extension if not exists pgcrypto;

create table if not exists public.staff_members (
  user_id     uuid primary key references auth.users (id) on delete cascade,
  role        text not null default 'staff' check (role in ('staff', 'admin')),
  display_name text not null default '',
  is_active   boolean not null default true,
  created_at  timestamptz not null default now()
);

create table if not exists public.ordering_settings (
  id          boolean primary key default true check (id),
  mode        text not null default 'approval_required' check (mode in (
    'closed', 'approval_required'
  )),
  updated_at  timestamptz not null default now(),
  updated_by  uuid references auth.users (id) on delete set null
);

insert into public.ordering_settings (id, mode)
values (true, 'approval_required')
on conflict (id) do nothing;

create table if not exists public.orders (
  id                    uuid primary key default gen_random_uuid(),
  order_number          bigint generated by default as identity unique,
  status_token_hash     text not null unique,
  idempotency_key       text not null unique,
  customer_first_name   text not null check (char_length(customer_first_name) between 1 and 60),
  fulfillment_location  text not null check (fulfillment_location in (
    'counter_pickup',
    'womens_prayer_hall_door',
    'womens_cafe_hall',
    'mens_cafe_hall'
  )),
  customer_note         text not null default '' check (char_length(customer_note) <= 500),
  payment_method        text not null check (payment_method in (
    'sumup_online',
    'card_on_fulfillment',
    'cash_on_fulfillment'
  )),
  payment_status        text not null check (payment_status in (
    'unpaid', 'pending', 'paid', 'failed', 'refunded'
  )),
  status                text not null check (status in (
    'awaiting_payment',
    'awaiting_staff_approval',
    'accepted',
    'preparing',
    'ready',
    'completed',
    'cancelled',
    'expired'
  )),
  total_cents           integer not null check (total_cents >= 0),
  currency              text not null default 'EUR' check (currency = 'EUR'),
  expires_at            timestamptz,
  accepted_at           timestamptz,
  completed_at          timestamptz,
  created_at            timestamptz not null default now(),
  updated_at            timestamptz not null default now(),
  constraint order_status_payment_method_check check (
    payment_method = 'sumup_online' or status <> 'awaiting_payment'
  )
);

create table if not exists public.order_items (
  id                uuid primary key default gen_random_uuid(),
  order_id          uuid not null references public.orders (id) on delete cascade,
  dish_id           text not null,
  name              jsonb not null,
  unit_price_cents  integer not null check (unit_price_cents >= 0),
  quantity          integer not null check (quantity between 1 and 99),
  line_total_cents  integer not null check (line_total_cents = unit_price_cents * quantity),
  created_at        timestamptz not null default now()
);

create table if not exists public.payment_attempts (
  id                    uuid primary key default gen_random_uuid(),
  order_id              uuid not null references public.orders (id) on delete cascade,
  checkout_reference    text not null unique,
  sumup_checkout_id     text unique,
  sumup_transaction_id  text,
  status                text not null default 'pending' check (status in (
    'pending', 'paid', 'failed', 'expired', 'refunded'
  )),
  amount_cents          integer not null check (amount_cents >= 0),
  created_at            timestamptz not null default now(),
  updated_at            timestamptz not null default now()
);

create table if not exists public.order_events (
  id          bigint generated by default as identity primary key,
  order_id    uuid not null references public.orders (id) on delete cascade,
  event_type  text not null,
  from_status text,
  to_status   text,
  actor_id    uuid references auth.users (id) on delete set null,
  metadata    jsonb not null default '{}',
  created_at  timestamptz not null default now()
);

create index if not exists orders_queue_idx
  on public.orders (status, created_at desc);
create index if not exists orders_payment_status_idx
  on public.orders (payment_status, created_at desc);
create index if not exists orders_expiry_idx
  on public.orders (expires_at)
  where status = 'awaiting_staff_approval';
create index if not exists order_items_order_idx on public.order_items (order_id);
create index if not exists payment_attempts_order_idx on public.payment_attempts (order_id);
create index if not exists order_events_order_idx on public.order_events (order_id, created_at);

create or replace function public.is_active_staff(required_role text default 'staff')
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.staff_members
    where user_id = auth.uid()
      and is_active
      and (required_role = 'staff' or role = required_role)
  );
$$;

create or replace function public.set_order_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists set_orders_updated_at on public.orders;
