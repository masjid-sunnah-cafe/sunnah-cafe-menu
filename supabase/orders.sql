create trigger set_payment_attempts_updated_at
before update on public.payment_attempts
for each row execute function public.set_order_updated_at();

create or replace function public.transition_order(
  target_order_id uuid,
  target_status text
)
returns public.orders
language plpgsql
security definer
set search_path = public
as $$
declare
  current_order public.orders;
  previous_status text;
begin
  if not public.is_active_staff('staff') then
    raise exception 'Not authorized';
  end if;

  select * into current_order
  from public.orders
  where id = target_order_id
  for update;

  if not found then
    raise exception 'Order not found';
  end if;

  if current_order.status = 'awaiting_staff_approval'
     and current_order.expires_at <= now() then
    raise exception 'Order approval window has expired';
  end if;

  if not (
    (current_order.status = 'awaiting_staff_approval' and (
      target_status = 'cancelled'
      or (current_order.payment_method = 'sumup_online' and target_status = 'awaiting_payment')
      or (current_order.payment_method <> 'sumup_online' and target_status = 'accepted')
    ))
    or (current_order.status = 'accepted' and target_status in ('ready', 'cancelled'))
    or (current_order.status = 'preparing' and target_status in ('ready', 'cancelled'))
    or (current_order.status = 'ready' and target_status = 'completed')
  ) then
    raise exception 'Invalid order status transition: % -> %', current_order.status, target_status;
  end if;

  if target_status = 'completed' and current_order.payment_status <> 'paid' then
    raise exception 'Order must be paid before completion';
  end if;

  previous_status := current_order.status;

  update public.orders
  set status = target_status,
      payment_status = case
        when target_status = 'awaiting_payment' then 'pending'
        else payment_status
      end,
      expires_at = case
        when target_status = 'awaiting_payment' then now() + interval '10 minutes'
        else expires_at
      end,
      accepted_at = case when target_status = 'accepted' then now() else accepted_at end,
      completed_at = case when target_status = 'completed' then now() else completed_at end
  where id = target_order_id
  returning * into current_order;

  insert into public.order_events (order_id, event_type, from_status, to_status, actor_id)
  values (target_order_id, 'status_changed', previous_status, target_status, auth.uid());

  return current_order;
end;
$$;

create or replace function public.set_ordering_mode(target_mode text)
returns public.ordering_settings
language plpgsql
security definer
set search_path = public
as $$
declare
  settings public.ordering_settings;
begin
  if not public.is_active_staff('staff') then
    raise exception 'Not authorized';
  end if;

  if target_mode not in ('closed', 'approval_required') then
    raise exception 'Invalid ordering mode';
  end if;

  update public.ordering_settings
  set mode = target_mode,
      updated_at = now(),
      updated_by = auth.uid()
  where id = true
  returning * into settings;

  return settings;
end;
$$;

create or replace function public.mark_fulfillment_payment_received(target_order_id uuid)
returns public.orders
language plpgsql
security definer
set search_path = public
as $$
declare
  current_order public.orders;
begin
  if not public.is_active_staff('staff') then
    raise exception 'Not authorized';
  end if;

  select * into current_order
  from public.orders
  where id = target_order_id
  for update;

  if not found then
    raise exception 'Order not found';
  end if;

  if current_order.payment_method not in ('card_on_fulfillment', 'cash_on_fulfillment')
     or current_order.status not in ('accepted', 'preparing', 'ready')
     or current_order.payment_status <> 'unpaid' then
    raise exception 'Order is not eligible for a fulfillment payment';
  end if;

  update public.orders
  set payment_status = 'paid'
  where id = target_order_id
  returning * into current_order;

  insert into public.order_events (order_id, event_type, actor_id)
  values (target_order_id, 'payment_received', auth.uid());

  return current_order;
end;
$$;

revoke all on function public.transition_order(uuid, text) from public, anon;
