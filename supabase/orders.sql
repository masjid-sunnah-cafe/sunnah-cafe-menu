revoke all on function public.mark_fulfillment_payment_received(uuid) from public, anon;
grant execute on function public.mark_fulfillment_payment_received(uuid) to authenticated;

create or replace function public.expire_unapproved_orders()
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  expired_count integer;
begin
  with expired as (
    update public.orders
    set status = 'expired'
    where status in ('awaiting_staff_approval', 'awaiting_payment')
      and expires_at <= now()
    returning id
  )
  select count(*) into expired_count from expired;

  return expired_count;
end;
$$;

create or replace function public.create_order_from_menu(
  customer_first_name text,
  fulfillment_location text,
  customer_note text,
  payment_method text,
  cart_items jsonb,
  request_id text,
  token_hash text
)
returns public.orders
language plpgsql
security definer
set search_path = public
as $$
declare
  created_order public.orders;
  calculated_total integer;
  requested_count integer;
  matched_count integer;
  ordering_mode text;
begin
  if jsonb_typeof(cart_items) <> 'array'
     or jsonb_array_length(cart_items) < 1
     or jsonb_array_length(cart_items) > 50 then
    raise exception 'Cart must contain between 1 and 50 rows';
  end if;

  select mode into ordering_mode
  from public.ordering_settings
  where id = true;

  if ordering_mode is null or ordering_mode = 'closed' then
    raise exception 'The cafe is not accepting orders right now';
  end if;

  select * into created_order
  from public.orders
  where idempotency_key = request_id;

  if found then
    if created_order.status_token_hash <> token_hash then
      raise exception 'Request identifier is already in use';
    end if;
    return created_order;
  end if;

  with requested as (
    select
      item->>'dishId' as dish_id,
      sum((item->>'quantity')::integer)::integer as quantity
    from jsonb_array_elements(cart_items) item
    group by item->>'dishId'
  ), priced as (
    select requested.dish_id, requested.quantity, dishes.price
    from requested
    join public.dishes on dishes.id = requested.dish_id
    where dishes.in_stock
      and requested.quantity between 1 and 99
  )
  select
    (select count(*) from requested),
    count(*),
    coalesce(sum(round(price * 100)::integer * quantity), 0)
  into requested_count, matched_count, calculated_total
  from priced;

  if requested_count <> matched_count then
    raise exception 'One or more products are unavailable or invalid';
  end if;

  insert into public.orders (
    status_token_hash,
    idempotency_key,
    customer_first_name,
    fulfillment_location,
    customer_note,
    payment_method,
    payment_status,
    status,
    total_cents,
    expires_at
  ) values (
    token_hash,
    request_id,
    trim(customer_first_name),
    fulfillment_location,
    coalesce(trim(customer_note), ''),
    payment_method,
    case
      'unpaid',
    'awaiting_staff_approval',
    calculated_total,
    case
      now() + interval '10 minutes'
    end
  )
  returning * into created_order;

  with requested as (
    select
      item->>'dishId' as dish_id,
      sum((item->>'quantity')::integer)::integer as quantity
    from jsonb_array_elements(cart_items) item
    group by item->>'dishId'
  )
  insert into public.order_items (
    order_id,
    dish_id,
    name,
    unit_price_cents,
    quantity,
    line_total_cents
  )
  select
    created_order.id,
    dishes.id,
    dishes.name,
    round(dishes.price * 100)::integer,
    requested.quantity,
    round(dishes.price * 100)::integer * requested.quantity
  from requested
  join public.dishes on dishes.id = requested.dish_id;

  insert into public.order_events (order_id, event_type, to_status)
  values (created_order.id, 'order_created', created_order.status);

  return created_order;
end;
$$;

create or replace function public.reconcile_sumup_payment(
  checkout_id text,
  remote_status text,
  transaction_id text,
  paid_amount_cents integer
)
returns public.orders
language plpgsql
security definer
set search_path = public
as $$
declare
  payment_attempt public.payment_attempts;
  target_order public.orders;
  previous_status text;
begin
  select * into payment_attempt
  from public.payment_attempts
  where sumup_checkout_id = checkout_id
  for update;

  if not found then
    raise exception 'Payment attempt not found';
  end if;

  select * into target_order
  from public.orders
  where id = payment_attempt.order_id
  for update;

  if remote_status = 'PAID' then
    if paid_amount_cents <> payment_attempt.amount_cents then
      raise exception 'Payment amount does not match order total';
    end if;

    if payment_attempt.status = 'paid' then
      return target_order;
    end if;

    previous_status := target_order.status;

    update public.payment_attempts
    set status = 'paid', sumup_transaction_id = transaction_id
    where id = payment_attempt.id;

    update public.orders
    set payment_status = 'paid',
        status = case when status = 'awaiting_payment' then 'accepted' else status end,
        accepted_at = case when status = 'awaiting_payment' then now() else accepted_at end
    where id = target_order.id
    returning * into target_order;

    insert into public.order_events (order_id, event_type, from_status, to_status, metadata)
    values (
      target_order.id,
      'sumup_payment_verified',
      previous_status,
      target_order.status,
      jsonb_build_object('checkoutId', checkout_id, 'transactionId', transaction_id)
    );
  elsif remote_status in ('FAILED', 'EXPIRED') and payment_attempt.status = 'pending' then
    update public.payment_attempts
    set status = lower(remote_status)
    where id = payment_attempt.id;

    update public.orders
    set payment_status = 'failed'
    where id = target_order.id
    returning * into target_order;

    insert into public.order_events (order_id, event_type, metadata)
    values (target_order.id, 'sumup_payment_failed', jsonb_build_object('checkoutId', checkout_id, 'status', remote_status));
  end if;

  return target_order;
end;
$$;

